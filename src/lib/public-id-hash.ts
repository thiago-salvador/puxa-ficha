/** Hash FNV-1a dos IDs públicos compactos; o cliente usa o mesmo para achar um ID original. */
export function hashPublicId(value: string): string {
  let hash = 0x811c9dc5
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index)
    hash = Math.imul(hash, 0x01000193)
  }
  return (hash >>> 0).toString(36)
}
